#!/usr/bin/env python3
"""The deko3d test pattern's shaders as a C++ header (docs/switch-port/16-deko3d-devlog.md, M2).

    python tools/switch-game/deko3d/gen_test_shaders.py --uam out/deko3d_tools/uam-build/uam.exe

Writes tools/switch-game/deko3d/test_shaders.h: each GLSL text and the DKSH the PC's uam (thirdparty/uam,
the same patched copy the NRO links) made of it. The console compiles the same text with its uam and
compares the bytes (nx_deko3d.cpp). Our own shaders, no game data.
"""
import argparse
import os
import subprocess
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))


def c_bytes(data):
    return ',\n'.join(', '.join(f'0x{b:02X}' for b in data[i:i + 16]) for i in range(0, len(data), 16))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--uam', required=True)
    a = ap.parse_args()
    out = ['// Generated by gen_test_shaders.py from test_pattern.{vert,frag}: do not edit.',
           '#pragma once', '#include <cstddef>', '#include <cstdint>', '', 'namespace theft4::nx_deko3d {', '']
    for name, stage in (('vert', 'vert'), ('frag', 'frag')):
        text = open(os.path.join(HERE, f'test_pattern.{name}'), encoding='utf-8').read().replace('\r\n', '\n')
        with tempfile.TemporaryDirectory() as tmp:
            src = os.path.join(tmp, 's.glsl')
            dst = os.path.join(tmp, 's.dksh')
            open(src, 'w', encoding='utf-8', newline='\n').write(text)
            r = subprocess.run([a.uam, '-s', stage, '-o', dst, src], capture_output=True, text=True)
            if r.returncode != 0:
                raise SystemExit(f'uam failed on {name}: {r.stdout}{r.stderr}')
            dksh = open(dst, 'rb').read()
        escaped = text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n"\n    "')
        out.append(f'inline constexpr const char kTestPattern_{name}_glsl[] =\n    "{escaped}";')
        out.append(f'inline constexpr uint8_t kTestPattern_{name}_dksh[] = {{\n{c_bytes(dksh)}}};')
        out.append('')
    out.append('}  // namespace theft4::nx_deko3d')
    open(os.path.join(HERE, 'test_shaders.h'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print('wrote test_shaders.h')


if __name__ == '__main__':
    main()
