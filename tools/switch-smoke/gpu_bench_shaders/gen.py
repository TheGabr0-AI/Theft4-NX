#!/usr/bin/env python3
"""Generates gpu_bench_shaders.h from the GLSL in this folder: SPIR-V for NVK
(glslangValidator -V, which defines VULKAN) and DKSH for deko3d (devkitPro's
uam, GLSL 4.60 without VULKAN). Same source, two compilers, as the benchmark
compares the two drivers (docs/switch-port/13-deko3d-spike.md, D.2).

Usage: gen.py <glslangValidator> <uam>   (run again after editing a shader;
the header is committed so the build needs neither tool).
"""
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SHADERS = [('quad.vert', 'vert'), ('textured.frag', 'frag'), ('gray.frag', 'frag'),
           ('fullscreen.vert', 'vert'), ('heavy.frag', 'frag')]


def c_name(file):
    return file.replace('.', '_')


def array(kind, name, data):
    if kind == 'spv':
        words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
        body = ',\n'.join('    ' + ', '.join(f'0x{w:08X}' for w in words[i:i + 8])
                          for i in range(0, len(words), 8))
        return f'alignas(4) const uint32_t kSpv_{name}[] = {{\n{body},\n}};\n'
    body = ',\n'.join('    ' + ', '.join(f'0x{b:02X}' for b in data[i:i + 16])
                      for i in range(0, len(data), 16))
    return f'alignas(256) const uint8_t kDksh_{name}[] = {{\n{body},\n}};\n'


def main():
    glslang, uam = sys.argv[1], sys.argv[2]
    out = ['// Generated by gen.py from the GLSL beside it; do not edit.\n',
           '#pragma once\n\n#include <cstdint>\n\nnamespace gpu_bench_shaders {\n\n']
    with tempfile.TemporaryDirectory() as tmp:
        for file, stage in SHADERS:
            src = os.path.join(HERE, file)
            spv = os.path.join(tmp, file + '.spv')
            dksh = os.path.join(tmp, file + '.dksh')
            subprocess.run([glslang, '-V', '--target-env', 'vulkan1.1', '-S', stage, '-o', spv, src],
                           check=True)
            subprocess.run([uam, '-s', stage, '-o', dksh, src], check=True)
            out.append(array('spv', c_name(file), open(spv, 'rb').read()))
            out.append(array('dksh', c_name(file), open(dksh, 'rb').read()))
            out.append('\n')
    out.append('}  // namespace gpu_bench_shaders\n')
    open(os.path.join(HERE, '..', 'gpu_bench_shaders.h'), 'w', newline='\n').write(''.join(out))


if __name__ == '__main__':
    main()
